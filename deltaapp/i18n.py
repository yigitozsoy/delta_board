_MONTHS = (("Oca", "Şub", "Mar", "Nis", "May", "Haz", "Tem", "Ağu", "Eyl", "Eki", "Kas", "Ara"),
           ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"))


def _idx():
    return 0 if prefs.get("language", "tr") == "tr" else 1


def t(key, **kw):
    v = S.get(key)
    if v is None:
        return key
    s = v[_idx()]
    return s.format(**kw) if kw else s


def month_short(m):
    return _MONTHS[_idx()][m - 1]
